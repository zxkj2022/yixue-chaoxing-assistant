'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const { compareVersions } = require('../src/core/updates');
const root = path.resolve(__dirname, '..');
const file = path.join(root, '易学·超星学习通助手.user.js');
const source = fs.readFileSync(file, 'utf8');
const metadata = JSON.parse(fs.readFileSync(path.join(root, 'src/metadata.json'), 'utf8'));
const runtimeRoot = path.dirname(require.resolve((process.env.PLAYWRIGHT_MODULE || 'playwright') + '/package.json'));
const { babelParse } = require(path.join(runtimeRoot, 'lib/transform/babelBundle.js'));
const parsed = babelParse(source, 'yixue.user.js', false);
const end = source.indexOf('// ==/UserScript==') + '// ==/UserScript=='.length;
const comments = parsed.comments.filter(c => c.start > end);
const longestLine = source.slice(end).split(/\r?\n/).reduce((max, line) => Math.max(max, line.length), 0);
assert.ok(longestLine <= 1000, `Installation code must be readable for review (longest line: ${longestLine})`);
assert.equal(compareVersions(metadata.version, require('../package.json').version), 0);
assert.equal(source.match(/^\/\/ @version\s+(.+)$/m)?.[1], metadata.version);
assert.equal(source.match(/^\/\/ @name\s+(.+)$/m)?.[1], metadata.name);
assert.match(source, /^\/\/ @author\s+三街网络$/m);
assert.match(source, /^\/\/ @antifeature\s+payment\s+.+$/m);
assert.match(source, /^\/\/ @license\s+禁止二开$/m);
assert.match(source, /^\/\/ @homepageURL\s+https:\/\/www\.yxzs\.love\/$/m);
assert.match(source, /^\/\/ @connect\s+api\.sanzwk\.com$/m);
assert.equal(source.match(/^\/\/ @icon\s+(.+)$/m)?.[1], metadata.icon);
assert.equal(source.match(/^\/\/ @icon64\s+(.+)$/m)?.[1], metadata.icon64);
assert.equal(metadata.icon64, metadata.icon);
assert.match(source, /^\/\/ @updateURL\s+https:\/\/raw\.githubusercontent\.com\/zxkj2022\/yixue-chaoxing-assistant\/main\/dist\/.+\.meta\.js$/m);
assert.match(source, /^\/\/ @downloadURL\s+https:\/\/raw\.githubusercontent\.com\/zxkj2022\/yixue-chaoxing-assistant\/main\/dist\/.+\.user\.js$/m);
assert.equal(/\u4e5d\u4e5d| supplied reference|working reference|参考脚本|参考版本/.test(source), false);
assert.doesNotMatch(metadata.name, /ABC|\u4e5d\u4e5d/i);
assert.equal(comments.filter(c => /Permission is hereby granted/.test(c.value)).length, 2);
assert.doesNotMatch(source, /\bwindow\.testLoad\s*=/);
assert.ok(!metadata.match.some(match => ['*://*/*', '<all_urls>'].includes(match)));
assert.ok(!metadata.connect.includes('*'));
new Function(source);
assert.equal((source.match(/\/\/ ==UserScript==/g) || []).length, 1, 'Only the actual header may contain metadata delimiters');
assert.equal((source.match(/\/\/ ==\/UserScript==/g) || []).length, 1, 'Runtime metadata delimiters are unsafe for marketplace rewrites');
const result = { version: metadata.version, bytes: Buffer.byteLength(source), sha256: createHash('sha256').update(source).digest('hex'), syntax: 'passed', metadata: 'passed', distributionMarkers: 'unique header only', longestLine, thirdPartyLicenses: 'present', forbiddenBrand: 'absent' };
fs.mkdirSync(path.join(root, 'artifacts'), { recursive: true });
fs.writeFileSync(path.join(root, 'artifacts/package-verification.json'), JSON.stringify(result, null, 2) + '\n');
console.log(JSON.stringify(result, null, 2));
